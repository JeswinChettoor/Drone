def point_lights_sdf():
    """
    A modest grid of indoor point lights layered on top of the directional
    'sun' so interior corridors aren't left completely unlit. Kept shadow-
    free to bound rendering cost; the directional light carries the shadows.
    """
    lights = []
    spacing = 5.0  # metres
    n = int(WORLD_WIDTH // spacing)
    idx = 0
    for i in range(1, n + 1):
        for j in range(1, n + 1):
            x = ORIGIN_X + i * spacing
            y = ORIGIN_Y - j * spacing
            lights.append(f"""
    <light type="point" name="ceiling_lamp_{idx:02d}">
      <pose>{x:.2f} {y:.2f} {WALL_HEIGHT - 0.1:.2f} 0 0 0</pose>
      <diffuse>0.9 0.85 0.7 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <attenuation>
        <range>6</range>
        <constant>0.6</constant>
        <linear>0.2</linear>
        <quadratic>0.05</quadratic>
      </attenuation>
      <cast_shadows>false</cast_shadows>
    </light>""")
            idx += 1
    return "".join(lights)


