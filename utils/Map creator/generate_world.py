import random

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------
CELL_SIZE = 0.1          # metres per grid cell (150 cells -> 15 m)
WALL_HEIGHT = 2.44       # metres
WALL_Z_CENTER = WALL_HEIGHT / 2.0
OUTPUT_FILE = "world.sdf"

ROWS = len(arena_map)
COLS = len(arena_map[0])
WORLD_WIDTH = COLS * CELL_SIZE     # x extent (m)
WORLD_DEPTH = ROWS * CELL_SIZE     # y extent (m)

# World-frame origin is placed at the centre of the arena so the generated
# world is symmetric about (0, 0, 0).
ORIGIN_X = -WORLD_WIDTH / 2.0
ORIGIN_Y = WORLD_DEPTH / 2.0

random.seed(42)  # deterministic slight material variation between walls


# ---------------------------------------------------------------------------
# 1. Merge adjacent '#' cells into a minimal set of rectangles
# ---------------------------------------------------------------------------
def merge_walls(grid):
    """
    Greedy maximal-rectangle merge.

    For every unvisited wall cell (scanned row-major) we:
      1. Grow the rectangle as far right as possible along the current row.
      2. Grow that same-width strip downward as far as every cell in each
         additional row is also an unvisited wall cell.
    This collapses large filled regions and long straight walls into a
    small number of box primitives instead of one box per 0.1 m cell,
    which keeps collision/visual geometry counts (and physics cost) low.
    """
    rows, cols = len(grid), len(grid[0])
    visited = [[False] * cols for _ in range(rows)]
    rects = []

    for r in range(rows):
        for c in range(cols):
            if grid[r][c] != "#" or visited[r][c]:
                continue

            # Extend right.
            c_end = c
            while c_end + 1 < cols and grid[r][c_end + 1] == "#" and not visited[r][c_end + 1]:
                c_end += 1

            # Extend down, only while the entire [c, c_end] strip is free wall.
            r_end = r
            while r_end + 1 < rows:
                row_ok = all(
                    grid[r_end + 1][cc] == "#" and not visited[r_end + 1][cc]
                    for cc in range(c, c_end + 1)
                )
                if not row_ok:
                    break
                r_end += 1

            for rr in range(r, r_end + 1):
                for cc in range(c, c_end + 1):
                    visited[rr][cc] = True

            rects.append((r, c, r_end, c_end))

    return rects


def rect_to_box(rect):
    """Convert a (r0, c0, r1, c1) grid rectangle into world-frame pose/size."""
    r0, c0, r1, c1 = rect

    left_x = ORIGIN_X + c0 * CELL_SIZE
    right_x = ORIGIN_X + (c1 + 1) * CELL_SIZE
    top_y = ORIGIN_Y - r0 * CELL_SIZE
    bottom_y = ORIGIN_Y - (r1 + 1) * CELL_SIZE

    width = right_x - left_x     # size along x
    depth = top_y - bottom_y     # size along y
    center_x = (left_x + right_x) / 2.0
    center_y = (top_y + bottom_y) / 2.0

    return {
        "width": width,
        "depth": depth,
        "center_x": center_x,
        "center_y": center_y,
    }


