def wall_material_sdf(material):
    return f"""        <material>
          <ambient>{material['ambient']}</ambient>
          <diffuse>{material['diffuse']}</diffuse>
          <specular>{material['specular']}</specular>
          <pbr>
            <metal>
              <albedo_map></albedo_map>
              <roughness>{material['roughness']}</roughness>
              <metalness>{material['metalness']}</metalness>
            </metal>
          </pbr>
        </material>
"""


def wall_model_sdf(index, box):
    material = random.choice(WALL_MATERIALS)
    name = f"wall_{index:03d}"
    return f"""
    <model name="{name}">
      <static>true</static>
      <pose>{box['center_x']:.4f} {box['center_y']:.4f} {WALL_Z_CENTER:.4f} 0 0 0</pose>
      <link name="link">
        <collision name="collision">
          <geometry>
            <box>
              <size>{box['width']:.4f} {box['depth']:.4f} {WALL_HEIGHT:.4f}</size>
            </box>
          </geometry>
          <surface>
            <friction>
              <ode>
                <mu>0.7</mu>
                <mu2>0.7</mu2>
              </ode>
            </friction>
            <contact>
              <ode>
                <kp>1e9</kp>
                <kd>1.0</kd>
                <max_vel>0.1</max_vel>
                <min_depth>0.001</min_depth>
              </ode>
            </contact>
            <bounce>
              <restitution_coefficient>0.0</restitution_coefficient>
              <threshold>1e6</threshold>
            </bounce>
          </surface>
        </collision>
        <visual name="visual">
          <geometry>
            <box>
              <size>{box['width']:.4f} {box['depth']:.4f} {WALL_HEIGHT:.4f}</size>
            </box>
          </geometry>
{wall_material_sdf(material)}        </visual>
      </link>
    </model>"""


